
-- ==========================================
-- SupportHub: Initial Database Schema
-- Flyway Migration V1
-- ==========================================

-- 1. Application Users
CREATE TABLE app_users (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    full_name VARCHAR(120) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,

    role VARCHAR(20) NOT NULL
        CHECK (role IN ('EMPLOYEE', 'TECHNICIAN', 'ADMIN')),

    enabled BOOLEAN NOT NULL DEFAULT TRUE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 2. Support Tickets
CREATE TABLE tickets (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),

    ticket_number BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,

    title VARCHAR(200) NOT NULL,
    description TEXT NOT NULL,

    status VARCHAR(20) NOT NULL DEFAULT 'OPEN'
        CHECK (status IN ('OPEN', 'IN_PROGRESS', 'RESOLVED', 'CLOSED')),

    priority VARCHAR(20) NOT NULL DEFAULT 'MEDIUM'
        CHECK (priority IN ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL')),

    category VARCHAR(100),

    created_by UUID NOT NULL REFERENCES app_users(id),

    assigned_to UUID REFERENCES app_users(id)
        ON DELETE SET NULL,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    resolved_at TIMESTAMPTZ
);

-- 3. Ticket Comments
CREATE TABLE ticket_comments (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),

    ticket_id UUID NOT NULL
        REFERENCES tickets(id) ON DELETE CASCADE,

    author_id UUID NOT NULL
        REFERENCES app_users(id),

    content TEXT NOT NULL,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 4. Ticket Activity History
CREATE TABLE ticket_history (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,

    ticket_id UUID NOT NULL
        REFERENCES tickets(id) ON DELETE CASCADE,

    changed_by UUID NOT NULL
        REFERENCES app_users(id),

    field_name VARCHAR(100) NOT NULL,
    old_value TEXT,
    new_value TEXT,

    changed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 5. Ticket Indexes
CREATE INDEX idx_tickets_status
    ON tickets(status);

CREATE INDEX idx_tickets_priority
    ON tickets(priority);

CREATE INDEX idx_tickets_created_by
    ON tickets(created_by);

CREATE INDEX idx_tickets_assigned_to
    ON tickets(assigned_to);

CREATE INDEX idx_tickets_created_at
    ON tickets(created_at);

-- 6. Comment Index
CREATE INDEX idx_ticket_comments_ticket_id
    ON ticket_comments(ticket_id);

-- 7. History Index
CREATE INDEX idx_ticket_history_ticket_id
    ON ticket_history(ticket_id);
